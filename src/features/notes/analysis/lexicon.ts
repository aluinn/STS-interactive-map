import type { EntryKind } from '../../../types'
import type { ItemCategory } from '../types'

/**
 * Small, hand-written dictionaries used for deterministic matching. They are
 * deliberately conservative: the review screen exists because rule-based
 * matching cannot understand an argument, only recognise familiar vocabulary.
 */

export interface LexiconTerm {
  /** Lower-case phrase to look for (hyphens and spaces are interchangeable). */
  term: string
  category: ItemCategory
  /** Further spellings. */
  aliases?: string[]
  /** Subject-area ids (see utils/areas) this term suggests. */
  topics?: string[]
}

const c = (term: string, category: ItemCategory, topics?: string[], aliases?: string[]) => ({
  term,
  category,
  ...(topics ? { topics } : {}),
  ...(aliases ? { aliases } : {}),
})

