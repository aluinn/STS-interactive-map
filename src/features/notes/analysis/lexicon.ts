export function kindForCategory(category: ItemCategory): EntryKind {
  switch (category) {
    case 'person':
      return 'person'
    case 'institution':
      return 'institution'
    case 'publication':
      return 'text'
    case 'technology':
    case 'instrument':
      return 'instrument'
    case 'event':
      return 'event'
    case 'place':
      return 'event'
    default:
      return 'idea'
  }
}
